// Helpers shared by build.mjs and dev.mjs.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { join, basename } from 'node:path';

const fromUrl = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
// import.meta.url is rewritten by some runners (vitest); the repo root is also where npm runs the scripts.
export const root = existsSync(join(fromUrl, 'package.json')) ? fromUrl : process.cwd();
const p = (...a) => join(root, ...a);

/** { name: path } for every src/components/<category>/<name>/<name>.ts */
export function componentEntries() {
  const out = {};
  const base = p('src/components');
  if (!existsSync(base)) return out;
  for (const cat of readdirSync(base)) {
    if (!statSync(join(base, cat)).isDirectory()) continue;
    for (const name of readdirSync(join(base, cat))) {
      const file = join(base, cat, name, `${name}.ts`);
      if (existsSync(file)) out[name] = file;
    }
  }
  return out;
}

function cssFilesIn(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((d) => (d.isDirectory() ? cssFilesIn(join(dir, d.name)) : d.name.endsWith('.css') ? [join(dir, d.name)] : []))
    .sort();
}

/** Writes optikos.css (tokens + layouts + all components), css/<name>.css and themes/*.css into outDir. */
export function buildCss(outDir) {
  mkdirSync(join(outDir, 'css'), { recursive: true });
  mkdirSync(join(outDir, 'themes'), { recursive: true });
  const read = (f) => readFileSync(f, 'utf8');
  const parts = [p('src/themes/base.css'), ...cssFilesIn(p('src/core')), ...cssFilesIn(p('src/layout')), ...cssFilesIn(p('src/components')), ...cssFilesIn(p('src/motion'))].filter(existsSync);
  writeFileSync(join(outDir, 'optikos.css'), parts.map(read).join('\n'));
  for (const f of parts) writeFileSync(join(outDir, 'css', basename(f)), read(f));
  for (const f of cssFilesIn(p('src/themes'))) if (basename(f) !== 'base.css') writeFileSync(join(outDir, 'themes', basename(f)), read(f));
}

/** Rewrites src/index.ts: core, data, themes and one export line per component (generated; do not edit by hand). */
export function genIndex() {
  const lines = ["// Generated by scripts/lib.mjs genIndex(). Run `npm run gen` after adding a component.", "export * from './core/index';", "export * from './data/index';", "export * from './themes/index';", "export * from './motion/index';", "export * from './ui/index';"];
  for (const file of Object.values(componentEntries())) lines.push(`export * from './${file.slice(p('src').length + 1, -3)}';`);
  const out = lines.join('\n') + '\n';
  const target = p('src/index.ts');
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) writeFileSync(target, out);
}

const SANDBOX_ORDER = ['base', 'layout', 'fields', 'form', 'data', 'overlays', 'navigation', 'feedback', 'dates', 'chat'];

/**
 * Every sandbox and demo with its sections (read from `.section('Title'` calls) and, for demos, the first-line comment.
 * The dev frame and the index page read this instead of listing directories in the browser.
 */
export function listPages() {
  const out = [];
  for (const [kind, folder] of [['sandbox', 'sandbox'], ['demo', 'demos']]) {
    const base = p(folder);
    if (!existsSync(base)) continue;
    const names = readdirSync(base, { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(join(base, d.name, 'main.ts'))).map((d) => d.name);
    if (kind === 'sandbox') names.sort((a, b) => (SANDBOX_ORDER.indexOf(a) + 1 || 99) - (SANDBOX_ORDER.indexOf(b) + 1 || 99) || a.localeCompare(b));
    else names.sort();
    for (const name of names) {
      const src = readFileSync(join(base, name, 'main.ts'), 'utf8');
      out.push({
        kind,
        name,
        href: `/${folder}/${name}/`,
        sections: [...src.matchAll(/\.section\(\s*(['"`])(.+?)\1/g)].map((m) => m[2]),
        description: (src.match(/^\/\/\s*(.+)$/m) ?? [])[1] ?? '',
      });
    }
  }
  return out;
}

export function writePages(outDir) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'pages.json'), JSON.stringify(listPages(), null, 2));
}
