// Helpers shared by build.mjs and dev.mjs.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { join, basename } from 'node:path';

const fromUrl = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
// import.meta.url is rewritten by some runners (vitest); the repo root is also where npm runs the scripts.
export const root = existsSync(join(fromUrl, 'package.json')) ? fromUrl : process.cwd();
const p = (...a) => join(root, ...a);

/** { name: path } for every src/components/<category>/<name>/<name>.ts */
export function componentEntries() {
  const out = {};
  const base = p('src/components');
  if (!existsSync(base)) return out;
  for (const cat of readdirSync(base)) {
    if (!statSync(join(base, cat)).isDirectory()) continue;
    for (const name of readdirSync(join(base, cat))) {
      const file = join(base, cat, name, `${name}.ts`);
      if (existsSync(file)) out[name] = file;
    }
  }
  return out;
}

function cssFilesIn(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((d) => (d.isDirectory() ? cssFilesIn(join(dir, d.name)) : d.name.endsWith('.css') ? [join(dir, d.name)] : []))
    .sort();
}

/**
 * Writes optikos.css (tokens + layouts + all components), css/<name>.css and themes/*.css into outDir.
 * `devThemes` also writes the dev-only themes of dev/themes/ (never shipped or on the public site).
 */
export function buildCss(outDir, { devThemes = false } = {}) {
  mkdirSync(join(outDir, 'css'), { recursive: true });
  mkdirSync(join(outDir, 'themes'), { recursive: true });
  const read = (f) => readFileSync(f, 'utf8');
  const parts = [p('src/themes/base.css'), ...cssFilesIn(p('src/core')), ...cssFilesIn(p('src/layout')), ...cssFilesIn(p('src/components')), ...cssFilesIn(p('src/motion'))].filter(existsSync);
  writeFileSync(join(outDir, 'optikos.css'), parts.map(read).join('\n'));
  for (const f of parts) writeFileSync(join(outDir, 'css', basename(f)), read(f));
  const themes = [...cssFilesIn(p('src/themes')), ...(devThemes ? cssFilesIn(p('dev/themes')) : [])];
  for (const f of themes) if (basename(f) !== 'base.css') writeFileSync(join(outDir, 'themes', basename(f)), read(f));
}

/** Rewrites src/index.ts: core, data, themes and one export line per component (generated; do not edit by hand). */
export function genIndex() {
  const lines = ["// Generated by scripts/lib.mjs genIndex(). Run `npm run gen` after adding a component.", "export * from './core/index';", "export * from './data/index';", "export * from './themes/index';", "export * from './motion/index';", "export * from './ui/index';", "export * from './build/index';"];
  for (const file of Object.values(componentEntries())) lines.push(`export * from './${file.slice(p('src').length + 1, -3)}';`);
  const out = lines.join('\n') + '\n';
  const target = p('src/index.ts');
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) writeFileSync(target, out);
}

const SANDBOX_ORDER = ['base', 'layout', 'fields', 'form', 'data', 'overlays', 'navigation', 'feedback', 'dates', 'chat'];

/**
 * Every sandbox and demo with its sections (read from `.section('Title'` calls) and, for demos, the first-line comment.
 * The dev frame and the index page read this instead of listing directories in the browser.
 */
export function listPages() {
  const out = [];
  for (const [kind, folder] of [['sandbox', 'sandbox'], ['demo', 'demos']]) {
    const base = p(folder);
    if (!existsSync(base)) continue;
    const names = readdirSync(base, { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(join(base, d.name, 'main.ts'))).map((d) => d.name);
    if (kind === 'sandbox') names.sort((a, b) => (SANDBOX_ORDER.indexOf(a) + 1 || 99) - (SANDBOX_ORDER.indexOf(b) + 1 || 99) || a.localeCompare(b));
    else names.sort();
    for (const name of names) {
      const src = readFileSync(join(base, name, 'main.ts'), 'utf8');
      out.push({
        kind,
        name,
        href: `/${folder}/${name}/`,
        sections: [...src.matchAll(/\.section\(\s*(['"`])(.+?)\1/g)].map((m) => m[2]),
        description: (src.match(/^\/\/\s*(.+)/) ?? [])[1] ?? '', // the file's first line, when it is a comment
      });
    }
  }
  return out;
}

export function writePages(outDir) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'pages.json'), JSON.stringify(listPages(), null, 2));
}

/**
 * Rewrites src/dev/keys.ts: for every registered component type, the option names its config accepts (read from the
 * `...Config` interfaces and their `extends`). `optikos/dev` compares a config against it to warn about ignored options.
 */
export function genKeys() {
  const src = (f) => readFileSync(f, 'utf8');
  const files = [p('src/core/component.ts'), p('src/core/container.ts'), p('src/core/field.ts'), ...Object.values(componentEntries())];
  const ifaces = {}; // name → { own: [...], parents: [...] }
  const classes = {}; // name → { config?: string, parent?: string }
  const types = {}; // type → class
  for (const f of files) {
    const text = src(f);
    for (const m of text.matchAll(/export interface (\w+)(?:<[^{]*?>)?\s+extends ([^{]+)\{\n([\s\S]*?)\n\}/g)) {
      const own = [...m[3].matchAll(/^  (?:readonly )?([A-Za-z_]\w*)\??:/gm)].map((x) => x[1]);
      ifaces[m[1]] = { own, parents: [...m[2].matchAll(/(\w+)(?:<[^>]*>)?/g)].map((x) => x[1]) };
    }
    for (const m of text.matchAll(/export interface (\w+)\s*\{\n([\s\S]*?)\n\}/g)) ifaces[m[1]] ??= { own: [...m[2].matchAll(/^  (?:readonly )?([A-Za-z_]\w*)\??:/gm)].map((x) => x[1]), parents: [] };
    for (const m of text.matchAll(/class (\w+)([^{]*?)\{/g)) {
      // the config is named in the class header, or else in its constructor's parameter
      const ctor = /constructor\(\s*\w+(?:\?)?: (\w+Config)\b/.exec(text.slice(m.index, text.indexOf('\nclass ', m.index + 1) >>> 0 || undefined))?.[1];
      classes[m[1]] = { parent: /extends (\w+)/.exec(m[2])?.[1], config: [...m[2].matchAll(/(\w+Config)\b/g)].map((x) => x[1]).pop() ?? ctor };
    }
    for (const m of text.matchAll(/register\('(\w+)', (\w+)\)/g)) types[m[1]] = m[2];
  }
  const collect = (name, seen = new Set()) => {
    if (!name || seen.has(name) || !ifaces[name]) return [];
    seen.add(name);
    return [...ifaces[name].own, ...ifaces[name].parents.flatMap((x) => collect(x, seen))];
  };
  const configOf = (cls, depth = 0) => (classes[cls]?.config ?? (depth < 8 && classes[cls]?.parent ? configOf(classes[cls].parent, depth + 1) : undefined));
  const out = {};
  for (const [type, cls] of Object.entries(types)) {
    const cfg = configOf(cls);
    out[type] = [...new Set([...collect('ComponentConfig'), ...collect(cfg ?? 'ComponentConfig')])].sort();
  }
  const body = Object.entries(out).sort().map(([k, v]) => `  ${k}: '${v.join(' ')}',`).join('\n');
  const target = p('src/dev/keys.ts');
  const text = `// Generated by scripts/lib.mjs genKeys(). Run \`npm run gen\` after changing a config interface.\nexport const keys: Record<string, string> = {\n${body}\n};\n`;
  mkdirSync(p('src/dev'), { recursive: true });
  if (!existsSync(target) || readFileSync(target, 'utf8') !== text) writeFileSync(target, text);
}
